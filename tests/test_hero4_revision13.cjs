const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const skills=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/skills.json'),'utf8'));
const skill=id=>skills.find(s=>s.id===`hero_4_skill_${id}`);
const first=skill(1),second=skill(2),fourth=skill(4);
assert.deepEqual(first.levels.map(l=>l.effects.find(e=>e.id==='poison').dps_pct),[12.5,15,17.5,20,22.5]);
assert.deepEqual(first.levels.map(l=>l.effects.find(e=>e.id==='poison').duration),[2,2,2,2,2]);
assert.deepEqual(first.levels.map(l=>l.stats.damage_pct),[20,22.5,25,27.5,30]);
first.levels.forEach(l=>assert(l.description_rows.includes(`Poison ${l.effects.find(e=>e.id==='poison').dps_pct}% ATK/s for 2s`)));
assert.deepEqual(second.levels.map(l=>l.stats.vfx_scale),[.117,.1235,.12675,.13,.1365]);
assert.deepEqual(second.levels.map(l=>l.stats.damage_min_range_multiplier),[.3,.3,.3,.3,.3]);
assert.deepEqual(second.levels.map(l=>l.stats.radius),[30,31,32,33,34]);
assert.equal(fourth.createria_unlock.level,15);
assert.equal(fourth.hero_level_unlock,30);
console.log('PASS C196 v1.3/v1.4: preserved poison/description curves, +30% art, halved Skill1 direct damage, unchanged hitboxes/piercing and distinct unlocks');
